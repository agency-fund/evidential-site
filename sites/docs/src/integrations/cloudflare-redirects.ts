/**
 * Writes dist/_redirects, which Cloudflare's Workers Static Assets read as 301 rules applied before any file is
 * served, from the redirect map in src/redirects.ts. Astro's own `redirects` (fed from the same map) only write
 * meta-refresh pages on a static site; these rules make the deployed site answer with real permanent redirects, and
 * also cover URLs that aren't pages.
 */
import { writeFile } from "node:fs/promises";
import type { AstroIntegration } from "astro";
import { FILE_REDIRECTS, PAGE_REDIRECTS } from "../redirects";

export default function cloudflareRedirects(): AstroIntegration {
  return {
    name: "evidential:cloudflare-redirects",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const rules: string[] = [];
        for (const [from, to] of Object.entries(PAGE_REDIRECTS)) {
          // Rules match the path exactly, and old links use both forms.
          rules.push(`${from} ${to} 301`, `${from.replace(/\/$/, "")} ${to} 301`);
        }
        for (const [from, to] of Object.entries(FILE_REDIRECTS)) rules.push(`${from} ${to} 301`);
        const header = "# Generated by src/integrations/cloudflare-redirects.ts from src/redirects.ts. Don't edit.\n";
        await writeFile(new URL("_redirects", dir), header + rules.join("\n") + "\n");
        logger.info(`wrote ${rules.length} redirect rules to _redirects`);
      },
    },
  };
}
